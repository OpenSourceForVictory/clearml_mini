"""Render the opt-in Nginx route map from the API priority manifest."""
import re
import sys

from .priority_routes import ROLES, manifest


BACKENDS = {
    'execution-control': 'execution-control-api:8000',
    'interaction': 'interaction-api:8000',
    'worker-data': 'worker-data-api:8000',
    'bulk-transfer': 'bulk-transfer-api:8000',
}


def _route_pattern(method, path):
    escaped = re.escape(path)
    return '~^' + method + ':' + re.sub(r'\\\{[^/{}]+\\\}', '[^/]+', escaped) + '$'


def render():
    """Exact paths precede variable paths; both are matched by method and URI."""
    entries = manifest()
    exact = sorted((method, path, category) for method, path, category, _, _ in entries
                   if '{' not in path)
    dynamic = sorted(((method, path, category) for method, path, category, _, _ in entries
                      if '{' in path), key=lambda item: (-len(re.sub(r'\{[^}]+\}', '', item[1])), item[0], item[1]))
    lines = ['# Generated by python -m backend.app.priority_gateway; do not edit route entries.',
             'map "$request_method:$uri" $priority_backend {',
             '    default interaction-api:8000;']
    for method, path, category in exact:
        lines.append(f'    {method}:{path} {BACKENDS[ROLES[category] or "interaction"]};')
    for method, path, category in dynamic:
        lines.append(f'    {_route_pattern(method, path)} {BACKENDS[ROLES[category] or "interaction"]};')
    lines.extend(['}', '', 'server {', '    listen 8000;', '    server_tokens off;',
                  '    client_max_body_size 0;', '    resolver 127.0.0.11 valid=5s ipv6=off;',
                  '    location / {',
                  '        proxy_pass http://$priority_backend$request_uri;',
                  '        include /etc/nginx/conf.d/proxy-common.inc;',
                  '    }', '}', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    sys.stdout.write(render())
