import {test,expect} from '@playwright/test';
test.skip(!process.env.SUITE_LIVE_TEST_API,'requires isolated API');
const base=process.env.SUITE_LIVE_TEST_API||'';
test('RoboTwin subset, drafts, publish, copies, export and archive through real API',async({page,request})=>{
  const login=await request.post(base+'/api/v1/auth/login',{data:{username:'admin',password:'suite-test-password'}});
  expect(login.ok()).toBeTruthy();
  const token=(await login.json()).access_token, headers={Authorization:'Bearer '+token};
  const name='suite-ui-'+Date.now();
  const t=await request.post(base+'/api/v1/admin/client-templates',{headers,data:{name,version:'1',image:'test:1',command:['true']}});
  expect(t.ok()).toBeTruthy();const template=(await t.json()).id;
  await page.addInitScript(t=>sessionStorage.setItem('eval-token',t),token);
  await page.goto(base);
  await page.getByRole('button',{name:'CS 评测批次',exact:true}).click();
  await page.getByRole('tab',{name:'评测集合管理',exact:true}).click();
  await page.getByRole('button',{name:'从 RoboTwin 预置创建'}).click();
  for(const task of ['adjust_bottle','beat_block_hammer','blocks_ranking_rgb'])await page.getByLabel('选择任务 '+task,{exact:true}).check();
  await page.getByRole('button',{name:'仅保留选中任务'}).click();
  await page.getByRole('button',{name:'选中当前显示任务'}).click();
  await page.getByLabel('批量回合数',{exact:true}).fill('2');
  await page.getByRole('button',{name:'应用到选中 3 项'}).click();
  await expect(page.getByText(/共 3 项、6 个回合/)).toBeVisible();
  await page.getByLabel('集合名称',{exact:true}).fill(name);
  await page.getByLabel('集合客户端模板',{exact:true}).selectOption(template);
  await page.getByLabel('集合标签（逗号分隔）').fill('smoke,robotwin');
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('草稿已保存。');
  await expect(page.getByRole('tabpanel',{name:'评测集合管理'})).toBeVisible();
  await page.getByLabel('集合说明',{exact:true}).fill('keep this draft');
  await page.getByRole('tab',{name:'客户端注册',exact:true}).click();
  await page.getByRole('tab',{name:'评测集合管理',exact:true}).click();
  await expect(page.getByLabel('集合说明',{exact:true})).toHaveValue('keep this draft');
  await page.getByRole('button',{name:'发布版本',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('集合版本已发布。');
  await expect(page.getByLabel('集合名称',{exact:true})).toBeDisabled();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出集合'}).click();
  const stream=await (await download).createReadStream();let text='';for await(const chunk of stream!)text+=chunk;
  const exported=JSON.parse(text);expect(exported.cases).toHaveLength(3);expect(exported.client.name).toBe(name);
  await page.getByRole('button',{name:'归档集合',exact:true}).click();
  await expect(page.getByRole('button',{name:'恢复集合'})).toBeVisible();
  await page.getByRole('button',{name:'恢复集合'}).click();
  await page.getByRole('button',{name:'创建新版本'}).click();
  await expect(page.getByLabel('集合版本',{exact:true})).toHaveValue('1-next');
  await page.getByRole('button',{name:'保存草稿',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('草稿已保存。');
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'删除草稿'}).click();
  await expect(page.getByRole('status')).toHaveText('草稿已删除。');
  await page.getByLabel('导入集合 JSON / YAML',{exact:true}).setInputFiles({name:'roundtrip.json',mimeType:'application/json',buffer:Buffer.from(text)});
  await expect(page.getByText(/发现相同任务内容/)).toBeVisible();
  await expect(page.getByLabel('集合客户端模板',{exact:true})).toHaveValue(template);
  // Finish with the original published test suite archived.
  const all=await request.get(base+'/api/v1/suites/manage?q='+name,{headers});
  for(const s of (await all.json()).items)await request.post(base+'/api/v1/suites/'+s.id+'/actions',{headers,data:{action:'archive',expected_revision:s.revision}});
  await page.screenshot({path:'test-results/suites-import.png',fullPage:true});
});

test('YAML defaults and field errors have no implicit persistence',async({page,request})=>{
  const login=await request.post(base+'/api/v1/auth/login',{data:{username:'admin',password:'suite-test-password'}});
  const token=(await login.json()).access_token;
  await page.addInitScript(t=>sessionStorage.setItem('eval-token',t),token);await page.goto(base);
  await page.getByRole('button',{name:'CS 评测批次',exact:true}).click();await page.getByRole('tab',{name:'评测集合管理',exact:true}).click();
  const upload=page.getByLabel('导入集合 JSON / YAML',{exact:true});
  await upload.setInputFiles({name:'bad.yaml',mimeType:'application/yaml',buffer:Buffer.from('cases:\n  - task_name: task\n    episodes: 0\n')});
  await expect(page.getByRole('alert')).toContainText('cases.0.episodes');
  await upload.setInputFiles({name:'ok.yaml',mimeType:'application/yaml',buffer:Buffer.from('name: imported\nversion: "1"\ndefaults: {episodes: 2, seed: 4}\ncases:\n  - task_name: one\n  - task_name: two\n')});
  await expect(page.getByText('校验通过：2 项 / 4 回合。')).toBeVisible();
  await expect(page.getByLabel('任务标识 0',{exact:true})).toHaveValue('case-001');
  await expect(page.getByRole('status')).toContainText('尚未保存');
});
